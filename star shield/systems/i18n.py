def t(key, **kwargs):
    """Текст по ключу на текущем языке (если нет перевода - английский, затем сам ключ)."""
    table = STRINGS.get(config.settings.get("language", "ru"), STRINGS["ru"])
    text = table.get(key)
    if text is None:
        text = STRINGS["en"].get(key, key)
    if kwargs and isinstance(text, str):
        text = text.format(**kwargs)
    return text
